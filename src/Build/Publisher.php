<?php

declare(strict_types=1);

namespace AiAccel\Build;

/**
 * Turns the manifest into what the running application reads:
 *
 *   php/<id>.php   guarded copies of the source files
 *   runtime.php    class -> guarded copy, method -> module (opcache-friendly PHP array)
 *   preload.php    for opcache.preload, so FFI works under ffi.enable=preload
 */
final class Publisher
{
    public function __construct(
        private readonly string $cacheDir,
        private readonly Transformer $transformer = new Transformer(),
    ) {
    }

    /**
     * @param bool $allowUnverified also publish modules built with --no-verify
     * @return int number of methods now served by C
     */
    public function publish(Manifest $manifest, bool $allowUnverified = false): int
    {
        $byFile = [];
        foreach ($manifest->all() as $key => $entry) {
            $usable = $entry['status'] === Manifest::VERIFIED || ($allowUnverified && $entry['status'] === Manifest::UNVERIFIED);
            if ($usable && is_file($entry['lib']) && is_file($entry['sourceFile'])) {
                $byFile[$entry['sourceFile']][$key] = $entry;
            }
        }

        $phpDir = $this->cacheDir . '/php';
        if (!is_dir($phpDir)) {
            mkdir($phpDir, 0775, true);
        }
        $map = ['classes' => [], 'modules' => []];
        $headers = [];
        $keep = [];
        foreach ($byFile as $file => $entries) {
            $guards = [];
            foreach ($entries as $key => $entry) {
                $guards[strtolower($key)] = [
                    'key' => $key,
                    'params' => array_column($entry['params'], 'name'),
                    'void' => $entry['return'] === 'void',
                ];
            }
            $result = $this->transformer->transform((string) file_get_contents($file), $file, $guards);
            if (!$result['guarded']) {
                continue;
            }
            $copy = $phpDir . '/' . substr(sha1($file), 0, 20) . '.php';
            $this->write($copy, $result['code']);
            $keep[$copy] = true;

            foreach ($result['classes'] as $class) {
                $map['classes'][$class] = ['php' => $copy, 'source' => $file, 'mtime' => filemtime($file)];
            }
            foreach ($result['guarded'] as $key) {
                $entry = $entries[$key];
                $map['modules'][$key] = [
                    'lib' => $entry['lib'],
                    'header' => $entry['header'],
                    'scope' => $entry['scope'],
                    'symbol' => $entry['symbol'],
                    'params' => $entry['params'],
                    'return' => $entry['return'],
                ];
                $headers[$entry['hfile']] = true;
            }
        }

        foreach (glob($phpDir . '/*.php') ?: [] as $old) {
            if (!isset($keep[$old])) {
                unlink($old);
            }
        }
        $this->write($this->cacheDir . '/runtime.php', "<?php\n\n// Generated by ai-c-compile. Do not edit.\nreturn " . var_export($map, true) . ";\n");
        $this->write($this->cacheDir . '/preload.php', $this->preloadScript(array_keys($headers)));
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($this->cacheDir . '/runtime.php', true);
        }

        return count($map['modules']);
    }

    /** @param list<string> $headers */
    private function preloadScript(array $headers): string
    {
        // Under ffi.enable=preload only preloaded code may call FFI, so the two classes that do are preloaded too.
        $classes = [dirname(__DIR__) . '/FFI/FFILoader.php', dirname(__DIR__) . '/FFI/NativeFunction.php'];

        return "<?php\n\n// Generated by ai-c-compile. Use as opcache.preload, or require it from your own preload script.\n"
            . 'foreach (' . var_export($headers, true) . " as \$header) {\n"
            . "    try {\n        \\FFI::load(\$header);\n    } catch (\\Throwable \$e) {\n"
            . "        error_log('ai-accel preload: ' . \$header . ': ' . \$e->getMessage());\n    }\n}\n"
            . 'foreach (' . var_export($classes, true) . " as \$file) {\n    opcache_compile_file(\$file);\n}\n";
    }

    private function write(string $path, string $content): void
    {
        $tmp = $path . '.' . getmypid() . '.tmp';
        file_put_contents($tmp, $content);
        rename($tmp, $path);
    }
}
